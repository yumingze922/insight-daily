  // 对话API：远程中转优先，无中转时用预置对话
  async startDialogue(eventId, phase) {
    const event = this.getEventById(eventId);
    if (!event) return null;

    // 如果有真实对话中转 API，调用它
    if (this.dialogueApi) {
      try {
        const resp = await fetch(`${this.dialogueApi}/start`, {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({
            news_id: eventId,
            news_title: event.title,
            news_summary: event.summary
          })
        });
        if (resp.ok) {
          const data = await resp.json();
          return { role: 'system', text: data.message, classical: null };
        }
      } catch (e) {
        console.log('⚠️ 对话中转不可用，使用预置对话');
      }
    }

    // 预置对话（每天 LLM 生成的、与当日新闻匹配的五阶段对话）
    await delay(500);
    const phaseData = event.dialogue.phases[phase - 1];
    return phaseData ? phaseData.messages[0] : null;
  },

  // 用户回答后获取系统回应：远程中转优先
  async respondDialogue(eventId, phase, userMessage, history) {
    const event = this.getEventById(eventId);

    if (this.dialogueApi) {
      try {
        const resp = await fetch(`${this.dialogueApi}/respond`, {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({
            news_id: eventId,
            news_title: event.title,
            news_summary: event.summary,
            phase: phase,
            user_message: userMessage,
            history: history || []
          })
        });
        if (resp.ok) {
          const data = await resp.json();
          return { text: data.message, phase_name: data.phase_name, fromApi: true };
        }
      } catch (e) {
        console.log('⚠️ 对话中转不可用，使用预置对话');
      }
    }

    // 预置对话：返回下一阶段的问题
    await delay(800);
    const nextPhase = event.dialogue.phases[phase];  // phase 是 0-based 当前阶段
    if (nextPhase) {
      return { text: nextPhase.messages[0].text, phase_name: nextPhase.name, fromApi: false };
    }
    return { text: null, phase_name: '总结', fromApi: false };
  },

  async generateNote(eventId) {
    await delay(600);
    const event = this.getEventById(eventId);
    return event ? event.dialogue.note : null;
  }
